`timescale 1ns / 1ps
// =====================================================================
//  pe — один processing element систолического массива (output-stationary).
//
//  Роль: это ОДИН MAC. Массив C = A·B строится из сетки таких PE, где
//  каждый PE(i,j) накапливает ровно один выходной элемент C[i][j].
//
//  Контракт (output-stationary dataflow):
//    - Активация a течёт СЛЕВА-НАПРАВО: a_in -> (регистр) -> a_out.
//    - Вес/операнд b течёт СВЕРХУ-ВНИЗ:  b_in -> (регистр) -> b_out.
//    - Каждый такт при en:  acc <= acc + a_in * b_in   (знаковый MAC).
//    - Пасс-through РЕГИСТРОВЫЙ: a доезжает до соседа справа за 1 такт,
//      b — до соседа снизу за 1 такт. Именно это создаёт систолический
//      «волновой фронт»: PE(i,j) видит валидную пару (A[i][k],B[k][j])
//      на такте t = k + i + j (см. систолический skew в systolic_array.sv).
//    - Вне валидного окна на входах ПОДАЮТСЯ НУЛИ → нулевые произведения
//      не портят acc. Поэтому MAC можно делать безусловно (не гейтить по k).
//    - clear (1 такт, в простое) обнуляет acc и пасс-through регистры —
//      старт нового matmul.
//
//  Точность: вход DATA_WIDTH-бит ЗНАКОВЫЙ (INT8 по умолчанию),
//  аккумулятор ACC_WIDTH-бит знаковый (INT32). Произведение двух INT8 —
//  это 16 бит; при K до ~65536 сумма влезает в INT32 без переполнения
//  (граница проверяется в SVA и в модели).
//
//  КОНВЕЙЕР MAC (ради f_max): умножение и накопление РАЗНЕСЕНЫ по тактам,
//  чтобы за один такт делалась ЛИБО умножение, ЛИБО сложение, а не оба —
//  так частота упирается в один DSP48E2, а не в длинное mult+add облако.
//    stage1 (AREG/BREG): a_r <= a_in ; b_r <= b_in
//    stage2 (MREG):      prod_r <= a_r * b_r
//    stage3 (PREG):      acc <= acc + prod_r          ← рекуррентность (1 такт)
//  Итог: произведение входов такта t попадает в acc на такте t+3 → LATENCY=3
//  (было 1). Это классический размен latency↔f_max: +2 такта дренажа за
//  «родную» частоту DSP. ВАЖНО: сумму это НЕ меняет — те же произведения
//  просто ложатся в acc на 2 такта позже; систолический skew массива прежний.
//  Аккумуляторную петлю acc<=acc+… пайплайнить НЕЛЬЗЯ (обратная связь за 1
//  такт), но умножитель вынесен ИЗ неё (MREG) → в петле только быстрый сумматор.
// =====================================================================
module pe #(
    parameter int DATA_WIDTH = 8,
    parameter int ACC_WIDTH  = 32
) (
    input  logic                          clk,
    input  logic                          rst_n,
    input  logic                          clear,   // обнулить acc (старт нового matmul)
    input  logic                          en,      // продвинуть конвейер на такт
    input  logic signed [DATA_WIDTH-1:0]  a_in,    // от левого соседа (или с левого края)
    input  logic signed [DATA_WIDTH-1:0]  b_in,    // от верхнего соседа (или с верхнего края)
    output logic signed [DATA_WIDTH-1:0]  a_out,   // к правому соседу
    output logic signed [DATA_WIDTH-1:0]  b_out,   // к нижнему соседу
    output logic signed [ACC_WIDTH-1:0]   acc      // накопленный C[i][j]
);

  // Конвейерные регистры MAC. Пасс-through (a_out/b_out) — ОТДЕЛЬНЫЕ регистры:
  // они кормят соседей и держат систолический skew (1 такт/хоп), тогда как
  // a_r/b_r/prod_r кормят локальный умножитель. Vivado упаковывает a_r/b_r в
  // AREG/BREG, prod_r в MREG, acc в PREG одного DSP48E2.
  //
  // (* use_dsp = "yes" *): БЕЗ этого атрибута Vivado видит маленькое INT8×INT8
  // умножение и раскладывает его в LUT (DSP48 = 27×18, для 8×8 «жалко» занимать
  // целый блок) → синтез даёт DSP=0, ~100 LUT/PE. Атрибут форсирует MAC в
  // DSP48E2 → 1 DSP на PE. Это ВАЛИДИРУЕТ ресурс-прокси P2 (PE≈DSP) синтезом.
  // (⚠️ имя атрибута — вендор-специфично, Xilinx/AMD; см. UG901 «USE_DSP».)
  logic signed [DATA_WIDTH-1:0]   a_r, b_r;   // stage1: операнды (AREG/BREG)
  (* use_dsp = "yes" *)
  logic signed [2*DATA_WIDTH-1:0] prod_r;     // stage2: произведение (MREG)

  // СИНХРОННЫЙ reset (нет `negedge rst_n` в списке чувствительности): внутренние
  // регистры DSP48E2 поддерживают ТОЛЬКО синхронный сброс. С асинхронным Vivado
  // не смог бы упаковать a_r/b_r/prod_r/acc в AREG/BREG/MREG/PREG и оставил бы их
  // в fabric → DSP работал бы комбинаторно (~2 нс, ~500 МГц). Синхронный сброс →
  // регистры уходят В DSP → «родная» частота. Корректность держит `clear`.
  always_ff @(posedge clk) begin
    if (!rst_n) begin                       // СИНХРОННЫЙ (внутри @(posedge clk))
      a_out <= '0; b_out <= '0;
      a_r   <= '0; b_r   <= '0; prod_r <= '0;
      acc   <= '0;
    end else if (clear) begin               // старт нового matmul: флашим весь конвейер
      a_out <= '0; b_out <= '0;
      a_r   <= '0; b_r   <= '0; prod_r <= '0;
      acc   <= '0;
    end else if (en) begin
      a_out  <= a_in;                        // пасс-through вправо (skew, 1 такт)
      b_out  <= b_in;                        // пасс-through вниз   (skew, 1 такт)
      a_r    <= a_in;                        // stage1: регистр операнда A
      b_r    <= b_in;                        // stage1: регистр операнда B
      prod_r <= a_r * b_r;                   // stage2: знаковое произведение (MREG)
      acc    <= acc + ACC_WIDTH'(prod_r);    // stage3: накопление (PREG), петля 1 такт
    end
  end

endmodule
